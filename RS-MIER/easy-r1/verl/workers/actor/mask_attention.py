"""Mask-supervised SAYO attention metrics for dual-image Qwen3-VL rollouts.

The mask is reward-only metadata.  It is resized to the language-model visual
token grid and is never added to ``multi_modal_inputs``.
"""

import math
import os
import re
from functools import lru_cache
from typing import Any, Optional

import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image
from torch import nn

from .config import AttentionRewardConfig


CAPTURE_FLAG = "_easy_r1_capture_mask_attention_qk"
CAPTURED_QUERY = "_easy_r1_mask_attention_query"
CAPTURED_KEY = "_easy_r1_mask_attention_key"
CAPTURED_SCALING = "_easy_r1_mask_attention_scaling"
PERCEPTION_START_PATTERN = re.compile(r"<\s*perception\s*>", flags=re.IGNORECASE)
PERCEPTION_END_PATTERN = re.compile(r"<\s*/\s*perception\s*>", flags=re.IGNORECASE)


def find_last_text_attention(module: nn.Module) -> nn.Module:
    """Find the final decoder self-attention module without assuming FSDP layout."""
    candidates = [
        child
        for child in module.modules()
        if hasattr(child, "layer_idx") and hasattr(child, "q_proj") and hasattr(child, "k_proj")
    ]
    if not candidates:
        raise RuntimeError("Could not find a decoder self-attention module for mask attention capture.")

    return max(candidates, key=lambda child: int(getattr(child, "layer_idx", -1)))


def begin_qk_capture(attention_module: nn.Module) -> None:
    clear_qk_capture(attention_module)
    setattr(attention_module, CAPTURE_FLAG, True)


def end_qk_capture(attention_module: nn.Module) -> tuple[torch.Tensor, torch.Tensor, float]:
    setattr(attention_module, CAPTURE_FLAG, False)
    query = getattr(attention_module, CAPTURED_QUERY, None)
    key = getattr(attention_module, CAPTURED_KEY, None)
    scaling = getattr(attention_module, CAPTURED_SCALING, None)
    clear_qk_capture(attention_module)
    if query is None or key is None:
        raise RuntimeError(
            "The final-layer Q/K tensors were not captured. Ensure the mask-attention FlashAttention patch is active."
        )

    if scaling is None:
        scaling = query.size(-1) ** -0.5

    return query, key, float(scaling)


def clear_qk_capture(attention_module: nn.Module) -> None:
    for name in (CAPTURED_QUERY, CAPTURED_KEY, CAPTURED_SCALING):
        if hasattr(attention_module, name):
            delattr(attention_module, name)


def _find_subsequence(sequence: list[int], pattern: list[int], start: int = 0) -> int:
    if not pattern:
        return -1
    last_start = len(sequence) - len(pattern)
    for index in range(start, last_start + 1):
        if sequence[index : index + len(pattern)] == pattern:
            return index
    return -1


def build_perception_content_mask(
    responses: torch.Tensor,
    response_mask: torch.Tensor,
    perception_start_ids: list[int],
    perception_end_ids: list[int],
    tokenizer: Optional[Any] = None,
) -> torch.Tensor:
    """Return response positions strictly inside the first perception section.

    Tokenizers can merge the character immediately before a closing tag into
    the ``</`` token.  For example, Qwen tokenizes ``</perception>``,
    `` </perception>`` and ``.</perception>`` with three different first token
    ids.  When a tokenizer is available, locate the tags in decoded text and
    use fast-tokenizer character offsets to map the content back to the
    original response positions.  The fixed-id path remains for synthetic
    tests and callers that do not provide a tokenizer.
    """
    section_mask = torch.zeros_like(response_mask, dtype=torch.bool)
    for row in range(responses.size(0)):
        valid_length = int(response_mask[row].sum().item())
        tokens = responses[row, :valid_length].tolist()

        if tokenizer is not None:
            # Decode the original ids independently so every character span
            # remains attached to its source token.  Full decode followed by
            # re-encode is not safe for generated byte-fallback/Unicode ids:
            # some valid ids decode to a replacement character and therefore
            # encode back to a different id.
            token_pieces = tokenizer.batch_decode(
                [[token] for token in tokens],
                skip_special_tokens=False,
                clean_up_tokenization_spaces=False,
            )
            offsets = []
            decoded_parts = []
            cursor = 0
            for piece in token_pieces:
                decoded_parts.append(piece)
                offsets.append((cursor, cursor + len(piece)))
                cursor += len(piece)
            decoded = "".join(decoded_parts)

            opening_match = PERCEPTION_START_PATTERN.search(decoded)
            if opening_match is None:
                continue
            closing_match = PERCEPTION_END_PATTERN.search(decoded, opening_match.end())
            if closing_match is None or closing_match.start() <= opening_match.end():
                continue

            content_start = opening_match.end()
            content_end = closing_match.start()
            for position, (token_start, token_end) in enumerate(offsets):
                # Boundary-pair encoding can also merge ``>`` with the first
                # content character or the final punctuation with ``</``.
                # Keep every token that carries any content character.
                if token_end > content_start and token_start < content_end:
                    section_mask[row, position] = True
            continue

        opening = _find_subsequence(tokens, perception_start_ids)
        if opening < 0:
            continue
        content_start = opening + len(perception_start_ids)
        closing = _find_subsequence(tokens, perception_end_ids, start=content_start)
        if closing <= content_start:
            continue
        section_mask[row, content_start:closing] = True

    return section_mask & response_mask.bool()


@lru_cache(maxsize=256)
def _cached_mask_grid(path: str, height: int, width: int) -> tuple[np.ndarray, float]:
    if not os.path.isfile(path):
        raise FileNotFoundError(f"Target mask does not exist: {path}")

    with Image.open(path) as image:
        mask = np.asarray(image.convert("L"), dtype=np.uint8) > 0

    pixel_ratio = float(mask.mean())
    mask_tensor = torch.from_numpy(mask.astype(np.float32)).view(1, 1, *mask.shape)
    token_weights = F.interpolate(mask_tensor, size=(height, width), mode="area")[0, 0].numpy()
    return token_weights, pixel_ratio


def _normalise_mask_paths(target_mask: Any, target_masks: Any) -> list[Optional[str]]:
    if target_masks is not None:
        if isinstance(target_masks, np.ndarray):
            target_masks = target_masks.tolist()
        if isinstance(target_masks, (tuple, list)):
            paths = [str(path) if path else None for path in target_masks]
            if len(paths) == 1:
                return paths * 2
            if len(paths) == 2:
                return paths
            raise ValueError(f"target_masks must contain one or two paths, got {len(paths)}.")

    if target_mask:
        path = str(target_mask)
        return [path, path]

    return [None, None]


def _as_bool(value: Any, default: bool = True) -> bool:
    if value is None:
        return default
    if isinstance(value, str):
        return value.strip().lower() not in {"", "0", "false", "no"}
    return bool(value)


def _categorical_entropy(logits: torch.Tensor, chunk_size: int = 16) -> torch.Tensor:
    """Compute entropy without retaining a float32 [tokens, vocab] temporary for all tokens."""
    entropy_parts = []
    for chunk in logits.split(chunk_size, dim=0):
        chunk = chunk.float()
        log_normalizer = torch.logsumexp(chunk, dim=-1)
        probabilities = torch.softmax(chunk, dim=-1)
        entropy_parts.append(log_normalizer - torch.sum(probabilities * chunk, dim=-1))
    return torch.cat(entropy_parts, dim=0)


def _single_image_metrics(
    mean_attention: torch.Tensor,
    image_positions: torch.Tensor,
    mask_weights: torch.Tensor,
    config: AttentionRewardConfig,
) -> dict[str, torch.Tensor]:
    """Compute the official SAYO target/all-image attention ratio for one image.

    ``mean_attention`` has already been averaged over attention heads and the
    selected high-entropy perception queries.  A soft mask is used so that a
    target crossing visual-token boundaries contributes proportionally.

    """
    image_attention = mean_attention[image_positions]
    target_weight_sum = mask_weights.sum()
    target_attention = torch.sum(image_attention * mask_weights) / target_weight_sum.clamp_min(config.epsilon)
    all_image_attention = image_attention.mean()
    attention_ratio = (target_attention + config.epsilon) / (all_image_attention + config.epsilon)
    score = torch.tanh(torch.log(attention_ratio))

    return {
        "score": score,
        "target_attention": target_attention,
        "all_image_attention": all_image_attention,
        "attention_ratio": attention_ratio,
    }


def _empty_metrics(batch_size: int, device: torch.device) -> dict[str, torch.Tensor]:
    names = (
        "attention_reward",
        "attention_target_mean_t1",
        "attention_target_mean_t2",
        "attention_all_image_mean_t1",
        "attention_all_image_mean_t2",
        "attention_ratio_t1",
        "attention_ratio_t2",
        "attention_reward_t1",
        "attention_reward_t2",
        "attention_selected_tokens",
        "attention_valid",
    )
    return {name: torch.zeros(batch_size, dtype=torch.float32, device=device) for name in names}


@torch.no_grad()
def compute_dual_image_attention_metrics(
    *,
    input_ids: torch.Tensor,
    attention_mask: torch.Tensor,
    responses: torch.Tensor,
    response_mask: torch.Tensor,
    response_logits: torch.Tensor,
    query_states: torch.Tensor,
    key_states: torch.Tensor,
    scaling: float,
    image_grid_thw: torch.Tensor,
    image_token_id: int,
    spatial_merge_size: int,
    perception_start_ids: list[int],
    perception_end_ids: list[int],
    target_mask: Optional[Any],
    target_masks: Optional[Any],
    attention_valid: Optional[Any],
    config: AttentionRewardConfig,
    tokenizer: Optional[Any] = None,
) -> dict[str, torch.Tensor]:
    """Compute the official SAYO attention reward independently for both images."""
    batch_size, sequence_length = input_ids.shape
    response_length = responses.size(1)
    device = input_ids.device
    metrics = _empty_metrics(batch_size, device)

    if query_states.shape[:1] != (batch_size,) or key_states.shape[:1] != (batch_size,):
        raise ValueError("Captured Q/K batch size does not match input_ids.")
    if query_states.size(2) != sequence_length or key_states.size(2) != sequence_length:
        raise ValueError("Captured Q/K sequence length does not match input_ids.")
    if image_grid_thw.ndim != 2 or image_grid_thw.size(0) != batch_size * 2:
        raise ValueError(
            f"Dual-image attention requires exactly two image grids per sample; got {tuple(image_grid_thw.shape)} "
            f"for batch size {batch_size}."
        )

    if key_states.size(1) != query_states.size(1):
        if query_states.size(1) % key_states.size(1) != 0:
            raise ValueError("The number of query heads must be divisible by the number of key/value heads.")
        key_states = key_states.repeat_interleave(query_states.size(1) // key_states.size(1), dim=1)

    perception_mask = build_perception_content_mask(
        responses,
        response_mask,
        perception_start_ids,
        perception_end_ids,
        tokenizer=tokenizer,
    )
    response_query_start = sequence_length - response_length - 1
    key_indices = torch.arange(sequence_length, device=device)

    target_mask_values = target_mask if target_mask is not None else [None] * batch_size
    target_masks_values = target_masks if target_masks is not None else [None] * batch_size
    valid_values = attention_valid if attention_valid is not None else [True] * batch_size

    for row in range(batch_size):
        if not _as_bool(valid_values[row]):
            continue

        content_positions = perception_mask[row].nonzero(as_tuple=False).flatten()
        if content_positions.numel() == 0:
            continue

        entropy = _categorical_entropy(response_logits[row, content_positions])
        selected_count = min(
            content_positions.numel(),
            max(config.min_selected_tokens, int(math.ceil(content_positions.numel() * config.entropy_top_ratio))),
        )
        selected_in_content = torch.topk(entropy, k=selected_count, largest=True).indices
        selected_response_positions = content_positions[selected_in_content]
        query_positions = response_query_start + selected_response_positions
        if (query_positions < 0).any() or (query_positions >= sequence_length).any():
            raise ValueError("Perception decision-state query positions are outside the captured sequence.")

        query = query_states[row, :, query_positions, :].float()
        key = key_states[row].float()
        scores = torch.einsum("hqd,hsd->hqs", query, key) * scaling
        causal_mask = key_indices.unsqueeze(0) <= query_positions.unsqueeze(1)
        valid_keys = causal_mask & attention_mask[row].bool().unsqueeze(0)
        scores = scores.masked_fill(~valid_keys.unsqueeze(0), torch.finfo(scores.dtype).min)
        attention = torch.softmax(scores, dim=-1)
        per_query_attention = attention.mean(dim=0)
        mean_attention = per_query_attention.mean(dim=0)
        grids = image_grid_thw[row * 2 : row * 2 + 2]
        prompt_length = sequence_length - response_length
        image_positions_all = (
            input_ids[row, :prompt_length] == image_token_id
        ).nonzero(as_tuple=False).flatten()
        token_counts = [
            int(grid[0].item())
            * int(grid[1].item() // spatial_merge_size)
            * int(grid[2].item() // spatial_merge_size)
            for grid in grids
        ]
        if sum(token_counts) != image_positions_all.numel():
            raise ValueError(
                f"Image token count mismatch for row {row}: input_ids contain {image_positions_all.numel()}, "
                f"but image_grid_thw describes {token_counts}."
            )

        mask_paths = _normalise_mask_paths(target_mask_values[row], target_masks_values[row])
        image_results = []
        offset = 0
        for image_index, (grid, token_count, mask_path) in enumerate(zip(grids, token_counts, mask_paths)):
            image_positions = image_positions_all[offset : offset + token_count]
            offset += token_count
            if mask_path is None:
                image_results.append(None)
                continue

            temporal = int(grid[0].item())
            grid_height = int(grid[1].item() // spatial_merge_size)
            grid_width = int(grid[2].item() // spatial_merge_size)
            mask_grid, pixel_ratio = _cached_mask_grid(mask_path, grid_height, grid_width)
            mask_weights = torch.as_tensor(mask_grid, dtype=torch.float32, device=device).flatten().repeat(temporal)
            target_weight_sum = float(mask_weights.sum().item())
            mask_ratio = target_weight_sum / max(mask_weights.numel(), 1)
            if (
                target_weight_sum < config.min_mask_token_weight
                or pixel_ratio >= config.max_mask_ratio
                or mask_ratio >= config.max_mask_ratio
            ):
                image_results.append(None)
                continue

            result = _single_image_metrics(
                mean_attention,
                image_positions,
                mask_weights,
                config,
            )
            image_results.append(result)
            suffix = image_index + 1
            metrics[f"attention_target_mean_t{suffix}"][row] = result["target_attention"]
            metrics[f"attention_all_image_mean_t{suffix}"][row] = result["all_image_attention"]
            metrics[f"attention_ratio_t{suffix}"][row] = result["attention_ratio"]
            metrics[f"attention_reward_t{suffix}"][row] = result["score"]

        valid_results = [result for result in image_results if result is not None]
        # The objective is explicitly dual-temporal: never grant a one-image
        # fallback reward when either temporal mask cannot be evaluated.
        if len(valid_results) != 2:
            continue

        first_score, second_score = valid_results[0]["score"], valid_results[1]["score"]
        # Dual-image extension of the official single-image SAYO metric: each
        # temporal image receives its own target/all-image reward and both are
        # weighted equally.
        pair_reward = (first_score + second_score) / 2

        metrics["attention_reward"][row] = pair_reward
        metrics["attention_selected_tokens"][row] = float(selected_count)
        metrics["attention_valid"][row] = 1.0

    return metrics
